#!/usr/bin/env node
/**
 * gallery-build-vendor — generate `gallery/vendor.js`, the module table the
 * preview simulator hands a React-based skin bundle.
 *
 * The simulator evaluates every skin's prebuilt `lib/client.js` in-page through
 * a `__ModuleLoader__` shim. Skins whose client half imports React (aqua,
 * aurora) reach for modules the bare page cannot provide, so the shim answers a
 * fixed, generated allowlist instead of throwing for those specifiers:
 *
 *   react, react/jsx-runtime, react/jsx-dev-runtime,
 *   react-dom, react-dom/client, @deepseek-ai/dsh-client-store
 *
 * The bundle is built from THIS repository's pinned dependencies with esbuild
 * (resolved from the pnpm store; `absWorkingDir` is the Aqua skin so bare
 * specifiers resolve exactly like that skin's own build), minified, with
 * `process.env.NODE_ENV` defined as production. The result is a classic script
 * installing `window.__GALLERY_VENDOR__`; no network access, no CDN, no
 * runtime node_modules traversal — the gallery stays file://-safe.
 *
 * Nothing about the execution model changes: a skin bundle already runs in the
 * page, so the only new surface is which specifiers it can import. Unknown
 * specifiers still throw the simulator's existing error.
 *
 * Usage:
 *   node scripts/gallery-build-vendor            # write gallery/vendor.js
 *   node scripts/gallery-build-vendor --check     # fail when it is stale
 */

import { mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const GALLERY = path.join(ROOT, 'gallery')
const OUT = path.join(GALLERY, 'vendor.js')
/** Bare specifiers every React-based skin may import from the simulator. */
const VENDOR_SPECIFIERS = [
  'react',
  'react/jsx-runtime',
  'react/jsx-dev-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/dsh-client-store',
]
/** Skin whose node_modules tree resolves those specifiers (pnpm workspace). */
const RESOLVE_FROM = path.join(ROOT, 'packages', 'skins', 'aqua')
/** Entry source: one IIFE installing the registry global. */
const ENTRY = [
  ...VENDOR_SPECIFIERS.map((specifier, index) => `import * as mod${String(index)} from ${JSON.stringify(specifier)}`),
  '',
  'window.__GALLERY_VENDOR__ = {',
  ...VENDOR_SPECIFIERS.map((specifier, index) => `  ${JSON.stringify(specifier)}: mod${String(index)},`),
  '}',
  '',
].join('\n')

/** Load esbuild from the workspace's pnpm store (it is a transitive dep). */
function loadEsbuild() {
  try {
    return createRequire(path.join(ROOT, 'package.json'))('esbuild')
  } catch {
    /* fall through to the store lookup */
  }
  const store = path.join(ROOT, 'node_modules', '.pnpm')
  const candidates = readdirSync(store).filter(name => name.startsWith('esbuild@')).sort()
  const latest = candidates.at(-1)
  if (latest === undefined) throw new Error('gallery-build-vendor: esbuild not found in the pnpm store')
  const anchor = path.join(store, latest, 'node_modules', 'esbuild', 'package.json')
  return createRequire(anchor)('esbuild')
}

/** Build the vendor bundle and return its text. */
async function buildVendor() {
  const esbuild = loadEsbuild()
  const scratch = mkdtempSync(path.join(tmpdir(), 'gallery-vendor-'))
  try {
    const result = await esbuild.build({
      stdin: { contents: ENTRY, resolveDir: RESOLVE_FROM, sourcefile: 'gallery-vendor-entry.js', loader: 'js' },
      bundle: true,
      format: 'iife',
      platform: 'browser',
      target: 'chrome110',
      minify: true,
      define: { 'process.env.NODE_ENV': '"production"' },
      outfile: path.join(scratch, 'vendor.js'),
      logLevel: 'warning',
      metafile: true,
    })
    const text = readFileSync(path.join(scratch, 'vendor.js'), 'utf8')
    const inputs = Object.keys(result.metafile.inputs).length
    return { text, inputs }
  } finally {
    rmSync(scratch, { recursive: true, force: true })
  }
}

const check = process.argv.includes('--check')
const { text, inputs } = await buildVendor()
const banner = '/* AUTO-GENERATED by scripts/gallery-build-vendor — do not edit by hand.\n'
  + `   ${String(VENDOR_SPECIFIERS.length)} specifiers from ${String(inputs)} inputs: `
  + `${VENDOR_SPECIFIERS.join(', ')}.\n`
  + '   Regenerate with `node scripts/gallery-build-vendor`. */\n'
const next = banner + text

if (check) {
  const current = (() => {
    try {
      return readFileSync(OUT, 'utf8')
    } catch {
      return null
    }
  })()
  if (current !== next) {
    console.error('gallery-build-vendor --check: gallery/vendor.js is stale — run `node scripts/gallery-build-vendor`')
    process.exit(1)
  }
  console.log(`gallery-build-vendor --check: vendor.js is current (${String(statSync(OUT).size)} bytes)`)
  process.exit(0)
}

writeFileSync(OUT, next)
const size = statSync(OUT).size
console.log(`gallery-build-vendor: gallery/vendor.js ${String(size)} bytes from ${String(inputs)} inputs`)
for (const specifier of VENDOR_SPECIFIERS) console.log(`  ${specifier}`)
